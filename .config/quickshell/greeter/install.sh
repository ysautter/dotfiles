#!/bin/bash
# Install the quickshell login screen for greetd (see greeter/README.md).
#
#   sudo greeter/install.sh                       greeter only
#   sudo greeter/install.sh --autologin yannick   + log in automatically at boot
#                                                 and lock at once (LUKS machines)
#   greeter/install.sh --stage DIR                only build the greeter tree in DIR
#                                                 (for testing: QS_GREETER_DEMO=1 qs -p DIR)
#   sudo greeter/install.sh --update              copy the QML/compositor files again
#                                                 (keeps config.toml and the display manager)
set -euo pipefail

src="$(cd "$(dirname "$0")/.." && pwd)"
autologin=""
stage=""
update=0
while [ $# -gt 0 ]; do
    case "$1" in
        --autologin) autologin="$2"; shift ;;
        --stage) stage="$2"; shift ;;
        --update) update=1 ;;
        *) echo "unknown option: $1" >&2; exit 1 ;;
    esac
    shift
done

build_tree() {  # $1 = target dir
    install -d -m 755 "$1/config" "$1/components"
    install -m 644 "$src/greeter/shell.qml" "$1/shell.qml"
    install -m 644 "$src/config/Theme.qml" "$src/config/Colors.qml" "$1/config/"
    install -m 644 "$src/components/LockContent.qml" "$1/components/"
}

monitors_lua() {  # hyprlang monitor= lines on stdin -> hl.monitor({...}) lines
    awk -F, '
        /^[[:space:]]*monitor[[:space:]]*=/ {
            sub(/^[[:space:]]*monitor[[:space:]]*=[[:space:]]*/, "")
            gsub(/[[:space:]]/, "")
            n = split($0, f, ","); o = f[1]
            if (!(o in seen)) { seen[o] = 1; order[++cnt] = o }
            if (f[2] == "disable") { spec[o, "disabled"] = "true"; next }
            i = 2
            if (f[2] !~ /^(transform|mirror|vrr|bitdepth|addreserved)$/) {
                spec[o, "mode"] = "\"" f[2] "\""; spec[o, "position"] = "\"" f[3] "\""; spec[o, "scale"] = f[4]; i = 5
            }
            for (; i < n; i += 2) {
                k = f[i]; v = f[i + 1]
                if (k == "transform" || k == "vrr" || k == "bitdepth") spec[o, k] = v
                else if (k == "mirror" && v != "0") spec[o, k] = "\"" v "\""
            }
        }
        END {
            for (j = 1; j <= cnt; j++) {
                o = order[j]; s = "hl.monitor({ output = \"" o "\""
                split("disabled mode position scale transform vrr bitdepth mirror", ks, " ")
                for (q = 1; q <= 8; q++) if ((o, ks[q]) in spec) s = s ", " ks[q] " = " spec[o, ks[q]]
                print s " })"
            }
        }'
}

if [ -n "$stage" ]; then
    rm -rf "$stage"
    build_tree "$stage"
    echo "staged in $stage"
    exit 0
fi

[ "$(id -u)" -eq 0 ] || { echo "run with sudo" >&2; exit 1; }

pacman -S --needed --noconfirm greetd

# QML + compositor config
rm -rf /etc/greetd/quickshell
build_tree /etc/greetd/quickshell
# + the monitor layout of the user running the installer (hypr/monitors.conf,
# hyprlang `monitor=` lines -> hl.monitor{}); other outputs: preferred mode
hypr_user="${SUDO_USER:-root}"
monconf="$(getent passwd "$hypr_user" | cut -d: -f6)/.config/hypr/monitors.conf"
{
    cat "$src/greeter/hyprland.lua"
    echo
    echo "-- monitors: generated by install.sh from $monconf"
    echo 'hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })'
    [ -r "$monconf" ] && monitors_lua < "$monconf"
} > /etc/greetd/hyprland.lua
chmod 644 /etc/greetd/hyprland.lua
vdir=$(mktemp -d); chown greeter "$vdir"
verify=$(cd /tmp && runuser -u greeter -- env XDG_RUNTIME_DIR="$vdir" HOME=/var/cache/qs-greeter Hyprland --verify-config -c /etc/greetd/hyprland.lua 2>&1 || true)
rm -rf "$vdir"
echo "$verify" | grep -q "config ok" ||
    { echo "WARNING: /etc/greetd/hyprland.lua has errors:"; echo "$verify" | tail -5; }

# greeter's writable home (Hyprland/Qt caches, qs.log, last user/session)
install -d -m 755 -o greeter -g greeter /var/cache/qs-greeter

# per-user wallpaper/colours, written by scripts/greeter-sync.sh
install -d -m 755 /var/lib/qs-greeter
getent passwd | awk -F: '$3>=1000 && $3<60000 && $7 !~ /(nologin|false)$/ {print $1}' |
while read -r u; do
    install -d -m 755 -o "$u" -g "$(id -gn "$u")" "/var/lib/qs-greeter/$u"
done

[ "$update" -eq 1 ] && { echo "updated /etc/greetd/quickshell"; exit 0; }

# greetd config (old one kept as config.toml.bak)
[ -f /etc/greetd/config.toml ] && cp -n /etc/greetd/config.toml /etc/greetd/config.toml.bak
{
    cat <<EOF
# Written by ~/.config/quickshell/greeter/install.sh
[terminal]
vt = 1

[general]
# sessions are started as login shells by the greeter itself (like a TTY login);
# ~/.profile would otherwise run startx on tty1
source_profile = false

[default_session]
command = "env HOME=/var/cache/qs-greeter start-hyprland -- -c /etc/greetd/hyprland.lua"
user = "greeter"
EOF
    if [ -n "$autologin" ]; then
        shell=$(getent passwd "$autologin" | cut -d: -f7)
        cat <<EOF

# boot: log in $autologin right away (disk is LUKS-encrypted) - Hyprland starts
# locked, quickshell takes over the lock (QS_AUTOLOCK, overlays/Lock.qml)
[initial_session]
command = "$shell -l -c 'QS_AUTOLOCK=1 exec start-hyprland -- --locked-cmd true'"
user = "$autologin"
EOF
    fi
} > /etc/greetd/config.toml

# switch the display manager (takes effect at the next boot)
current=$(basename "$(readlink -f /etc/systemd/system/display-manager.service 2>/dev/null)" 2>/dev/null || true)
if [ -n "$current" ] && [ "$current" != "greetd.service" ] && [ "$current" != "display-manager.service" ]; then
    systemctl disable "$current"
fi
systemctl enable greetd.service
echo "done - greetd is used from the next boot on (old DM: ${current:-none})"
